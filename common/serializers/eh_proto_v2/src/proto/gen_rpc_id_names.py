"""Generate gen_v2_names.{c,h} (eh_rpc_id_name_v2()) from rpc_v2.proto: RpcId -> name
without the Req_/Resp_/Event_ prefix. One string pool; Req_X and Resp_X share an offset
table, so they must sit at the same offset from their base (checked here).

  gen_rpc_id_names.py           write src/gen_v2_names.c and include/gen_v2_names.h
  gen_rpc_id_names.py --check   exit 1 if they differ from what rpc_v2.proto generates
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PROTO = os.path.join(HERE, "rpc_v2.proto")
OUT_C = os.path.join(HERE, "..", "gen_v2_names.c")
OUT_H = os.path.join(HERE, "..", "..", "include", "gen_v2_names.h")

NO_NAME = 0xFFFF


def ids_of(body, prefix):
    out = {}
    for name, val in re.findall(r"(\w+)\s*=\s*(0x[0-9A-Fa-f]+|\d+)\s*;", body):
        if name.startswith(prefix) and name not in (prefix + "Base", prefix + "Max"):
            out[name[len(prefix):]] = int(val, 0)
    base = int(re.search(prefix + r"Base\s*=\s*(0x[0-9A-Fa-f]+|\d+)", body).group(1), 0)
    return {k: v - base for k, v in out.items()}


def generate(proto_path):
    body = re.search(r"enum\s+RpcId\s*\{(.*?)\}", open(proto_path).read(), re.S).group(1)
    body = re.sub(r"//[^\n]*|/\*.*?\*/", "", body, flags=re.S)
    req, resp, evt = ids_of(body, "Req_"), ids_of(body, "Resp_"), ids_of(body, "Event_")
    if req != resp:
        sys.exit("gen_rpc_id_names: Req_/Resp_ ids no longer mirror each other; "
                 "split the shared offset table")

    pool, offset = [], {}

    def off(name):
        if name not in offset:
            offset[name] = sum(len(s) + 1 for s in pool)
            pool.append(name)
        return offset[name]

    def table(ids):
        row = [None] * (max(ids.values()) + 1)
        for name, i in ids.items():
            row[i] = name
        return [(off(n), n) if n else (NO_NAME, "-") for n in row]

    req_resp, events = table(req), table(evt)
    assert sum(len(s) + 1 for s in pool) < NO_NAME

    out = ["/*",
           " * SPDX-FileCopyrightText: 2026 Espressif Systems (Shanghai) CO LTD",
           " * SPDX-License-Identifier: Apache-2.0",
           " */",
           "/*",
           " * Generated by proto/gen_rpc_id_names.py from rpc_v2.proto. DO NOT EDIT;",
           " * run src/proto/build_proto.sh after changing the proto.",
           " *",
           " * RpcId -> name without the Req_/Resp_/Event_ prefix. Each table holds 16-bit",
           " * offsets into one string pool (half the flash of a pointer table):",
           " *",
           " *   s_req_resp[id - Req_Base]  or  s_req_resp[id - Resp_Base]  (shared)",
           " *   s_event[id - Event_Base]",
           " *        |",
           " *        +--> offset --> s_pool: \"GetMACAddress\\0SetMacAddress\\0...\"",
           " *",
           " * NO_NAME marks an unused id; the lookup then returns NULL.",
           " */",
           "",
           "#include <stddef.h>",
           '#include "gen_v2.h"',
           '#include "gen_v2_names.h"',
           "",
           "#define NO_NAME 0xFFFF",
           "",
           "static const char s_pool[] ="]
    out += ['    "%s\\0"' % s for s in pool] + ["    ;", ""]
    for sym, rows in (("s_req_resp", req_resp), ("s_event", events)):
        out.append("static const uint16_t %s[] = {" % sym)
        out += ["    %s,%s/* %s */" % ("NO_NAME" if o == NO_NAME else o, " " * max(1, 8 - len(str(o))), n)
                for o, n in rows]
        out += ["};", ""]
    out += ["static const char *name_at(const uint16_t *t, size_t n, int32_t i)",
            "{",
            "    return (i >= 0 && (size_t)i < n && t[i] != NO_NAME) ? &s_pool[t[i]] : NULL;",
            "}",
            "",
            "const char *eh_rpc_id_name_v2(int32_t msg_id)",
            "{",
            "    const size_t n_rr = sizeof(s_req_resp) / sizeof(s_req_resp[0]);",
            "    const size_t n_ev = sizeof(s_event) / sizeof(s_event[0]);",
            "",
            "    if (msg_id >= RPC_ID__Event_Base) {",
            "        return name_at(s_event, n_ev, msg_id - RPC_ID__Event_Base);",
            "    }",
            "    if (msg_id >= RPC_ID__Resp_Base) {",
            "        return name_at(s_req_resp, n_rr, msg_id - RPC_ID__Resp_Base);",
            "    }",
            "    return name_at(s_req_resp, n_rr, msg_id - RPC_ID__Req_Base);",
            "}",
            ""]
    hdr = ["/*",
           " * SPDX-FileCopyrightText: 2026 Espressif Systems (Shanghai) CO LTD",
           " * SPDX-License-Identifier: Apache-2.0",
           " */",
           "/* Generated by proto/gen_rpc_id_names.py from rpc_v2.proto. DO NOT EDIT. */",
           "#ifndef GEN_V2_NAMES_H",
           "#define GEN_V2_NAMES_H",
           "",
           "#include <stdint.h>",
           "",
           "#ifdef __cplusplus",
           'extern "C" {',
           "#endif",
           "",
           "/* Short RpcId name without the Req_/Resp_/Event_ prefix (shared by a request and its",
           " * response), or NULL for an unknown id. */",
           "const char *eh_rpc_id_name_v2(int32_t msg_id);",
           "",
           "#ifdef __cplusplus",
           "}",
           "#endif",
           "",
           "#endif",
           ""]
    return {OUT_C: "\n".join(out), OUT_H: "\n".join(hdr)}


def main(argv):
    files = generate(PROTO)
    if "--check" in argv:
        stale = [p for p, text in files.items()
                 if not os.path.isfile(p) or open(p).read() != text]
        for p in stale:
            print(f"{os.path.relpath(p)} is out of date with rpc_v2.proto")
        if stale:
            print("run common/serializers/eh_proto_v2/src/proto/build_proto.sh")
        return 1 if stale else 0
    for p, text in files.items():
        open(p, "w").write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
